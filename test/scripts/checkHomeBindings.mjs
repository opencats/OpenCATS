/* Focused native journeys; uses seedRecruiterWorkflows.php in an explicitly disposable app. */
import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
assert.equal(process.env.OPENCATS_WORKFLOW_DISPOSABLE,'1');
const base = process.env.WORKFLOW_BASE_URL;
const app = process.env.WORKFLOW_APP_CONTAINER;
const dbContainer = process.env.WORKFLOW_DB_CONTAINER;
const network = process.env.WORKFLOW_NETWORK;
assert.ok(app && dbContainer && network);
const inspect = name=>JSON.parse(execFileSync('docker',['inspect',name],{encoding:'utf8'}))[0];
assert.equal(JSON.parse(execFileSync('docker',['network','inspect',network],{encoding:'utf8'}))[0].Internal,true);
const appNetwork = inspect(app).NetworkSettings.Networks[network];
assert.equal(new URL(base).hostname,appNetwork.IPAddress);
assert.ok(inspect(dbContainer).NetworkSettings.Networks[network]);
const output = process.env.WORKFLOW_EVIDENCE;
assert.ok(output);
mkdirSync(output,{recursive:true});
const db = sql=>execFileSync('docker',['exec',dbContainer,'mysql','-udev','-pdev','cats_test','--batch','--raw','-e',sql],{encoding:'utf8'});
assert.match(db('SELECT name FROM site'),/synthetic only/);
const browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH}:{})});
const context = await browser.newContext({timezoneId:'UTC',viewport:{width:1920,height:1080}});
context.setDefaultTimeout(15000);
await context.route('**/*',r=>new URL(r.request().url()).origin===new URL(base).origin?r.continue():r.abort());
await context.addInitScript(()=>{if(new URLSearchParams(location.search).has('fresh')) sessionStorage.clear();});
const page = await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const go = query=>page.goto(`${base}/index.php?${query}`);
const settled = ()=>page.waitForFunction(()=>!document.querySelector('.collapsing') && !document.querySelector('[data-home-activity-content][aria-busy]'));
try {
    await go('m=home&fresh=1');
    await page.locator('#username').fill('testerEdit');
    await page.locator('#password').fill('opencats-assessment-only');
    await page.locator('#loginForm').getByRole('button',{name:'Login',exact:true}).click();
    await page.waitForURL(url=>url.searchParams.get('m')==='home');
    assert.equal(await page.locator('.home-support section').count(),3);
    assert.match(await page.locator('#home-accounts-heading').locator('..').innerText(),/Westhaven Distribution.*Northbridge Precision/s);
    assert.match(await page.locator('#home-current-jobs').locator('..').innerText(),/2 of 2.*Warehouse Operatives.*CNC Maintenance Engineer/s);
    assert.match(await page.locator('#home-calendar-heading').locator('..').innerText(),/Alex Morgan - CNC technical interview/);
    let activityRequests=0;
    page.on('request',req=>{if(new URL(req.url()).searchParams.get('a')==='contextActivity') activityRequests++;});
    await go('m=home&fresh=1');
    assert.equal(activityRequests,0);
    const taskID = 'priority-task-970003';
    const panel = page.locator(`#context-${taskID}`);
    const measurements=[];
    for (const [width,height] of [[1920,1080],[1440,900],[1366,768],[1280,800],[1024,768],[390,844],[320,844]]) {
        await page.setViewportSize({width,height});
        await page.evaluate(()=>sessionStorage.clear());
        await go('m=home&fresh=1');
        await page.screenshot({path:resolve(output,`native-${width}-closed.png`)});
        await page.locator(`#${taskID} [data-home-context-toggle]`).click();
        await settled();
        assert.match(await panel.locator('.home-recent-activity').innerText(),/Alex confirmed CNC fault-finding experience/);
        assert.equal(await page.locator('[data-home-context].show').count(),1);
        await page.evaluate(()=>scrollTo(0,0));
        measurements.push(await page.evaluate(()=>({width:innerWidth,height:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth,firstRowTop:document.querySelector('#priorityRows > li').getBoundingClientRect().top,selected:document.querySelector('[data-home-context].show').id,rail:document.querySelector('#homeContextRail').hidden?0:document.querySelector('#homeContextRail').getBoundingClientRect().width})));
        await page.screenshot({path:resolve(output,`native-${width}-open.png`)});
        await page.screenshot({path:resolve(output,`native-${width}-full-page.png`),fullPage:true});
        await page.locator('.home-support').screenshot({path:resolve(output,`native-${width}-support.png`)});
    }
    assert.ok(measurements.every(m=>!m.overflow));
    await page.setViewportSize({width:1366,height:768});
    await go('m=home&fresh=1');
    await page.locator(`#${taskID} [data-home-context-toggle]`).click();
    await settled();
    const readsBeforeResize = activityRequests;
    const edit = panel.getByRole('link',{name:'Edit / Reschedule',exact:true});
    await edit.focus();
    await page.setViewportSize({width:1440,height:900});
    await page.waitForFunction(()=>!document.getElementById('homeContextRail').hidden);
    assert.equal(await edit.evaluate(e=>e===document.activeElement),true);
    assert.equal(activityRequests,readsBeforeResize);
    await page.keyboard.press('Escape');
    await panel.waitFor({state:'hidden'});
    const valid = `${base}/index.php?m=home&a=contextActivity&homeView=compact&filter=all&page=1&homeContext=${taskID}`;
    const response = await context.request.get(valid);
    assert.equal(response.headers()['x-home-activity'],'1');
    assert.match(await response.text(),/Alex confirmed/);
    for (const url of [valid.replace(taskID,'priority-task-999999'),valid.replace('page=1','page[]=1'),valid.replace('homeContext=','homeContext[]='),valid.replace('filter=all','filter=warnings')]) {
        const denied = await context.request.get(url);
        assert.equal(denied.headers()['x-home-activity'],undefined);
        assert.doesNotMatch(await denied.text(),/Alex confirmed/);
    }
    assert.equal((await context.request.post(valid)).headers()['x-home-activity'],undefined);
    // Follow the real native Calendar destination; preserve both associations.
    const calendarBefore = db("SELECT date,data_item_type,data_item_id,joborder_id FROM calendar_event WHERE title='Alex Morgan - CNC technical interview'");
    await go('m=home&fresh=1');
    const appointment = page.locator('[aria-label="Supporting work"]').getByRole('link',{name:'Alex Morgan - CNC technical interview',exact:true});
    await appointment.click();
    assert.equal(new URL(page.url()).searchParams.get('m'),'calendar');
    await page.locator('#viewEventTD').waitFor({state:'visible'});
    assert.match(await page.locator('#viewEventTitle').innerText(),/Alex Morgan/);
    assert.match(await page.locator('#viewEventLink').innerText(),/Alex Morgan/);
    assert.equal(db("SELECT date,data_item_type,data_item_id,joborder_id FROM calendar_event WHERE title='Alex Morgan - CNC technical interview'"),calendarBefore);
    // Native Task form, return state and modal completion; changes remain only in disposable records.
    await go('m=home&fresh=1');
    await page.locator(`#${taskID} [data-home-context-toggle]`).click();
    await settled();
    await edit.click();
    assert.equal(new URL(page.url()).searchParams.get('m'),'tasks');
    await page.getByRole('button',{name:'Save Task',exact:true}).click();
    await page.waitForURL(url=>url.searchParams.get('m')==='home');
    await settled();
    const first = page.locator('#priority-task-970001');
    await first.locator('[data-home-context-toggle]').click();
    await settled();
    const completion = page.locator('#context-priority-task-970001 [data-home-task]');
    await completion.click();
    await page.locator('#homeTaskComplete').getByRole('button',{name:'Cancel',exact:true}).click();
    await page.locator('#homeTaskComplete').waitFor({state:'hidden'});
    const evidenceBefore = db('SELECT (SELECT COUNT(*) FROM activity) AS activityCount,(SELECT COUNT(*) FROM candidate_joborder_status_history) AS progress');
    await completion.click();
    await page.locator('#homeTaskComplete').getByRole('button',{name:'Complete Task',exact:true}).click();
    await page.waitForURL(url=>url.searchParams.get('taskNotice')==='saved');
    assert.match(db('SELECT status,completed_by FROM task WHERE task_id=970001'),/completed\s+10003/);
    assert.equal(db('SELECT (SELECT COUNT(*) FROM activity) AS activityCount,(SELECT COUNT(*) FROM candidate_joborder_status_history) AS progress'),evidenceBefore);
    await go('m=home&a=priorities&filter=warnings&page=1&fresh=1');
    const review = page.locator('[data-home-context] button[name="reviewAction"][value="remind_later"]').first();
    // Review controls are inside their warning context.
    const reviewPanel = review.locator('xpath=ancestor::*[@data-home-context]');
    const reviewRow = await reviewPanel.getAttribute('data-home-row');
    await page.locator(`#${reviewRow} [data-home-context-toggle]`).click();
    await settled();
    await page.locator(`#context-${reviewRow} button[name="reviewAction"][value="remind_later"]`).first().click();
    await page.waitForURL(url=>url.searchParams.get('warningReview')==='saved');
    assert.match(db('SELECT action FROM warning_review WHERE reviewing_user=10003'),/remind_later/);
    assert.deepEqual(errors,[]);
    writeFileSync(resolve(output,'native-measurements.json'),JSON.stringify({measurements,activityRequests},null,2));
    console.log('PASS: real Home bindings, selected Activity and malformed/out-of-scope reads, native Task edit/return/completion, personal review, Calendar association destination, responsive single panel/focus and no repeated Activity on resize.');
} finally {await context.close(); await browser.close();}
